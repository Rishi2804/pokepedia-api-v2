-- Legends: Z-A and its Mega Dimension DLC -- data.
--
-- Split from 000006 because Postgres refuses to *use* an enum label added by
-- the same transaction ("unsafe use of new value of enum type"). PG 12+ allows
-- ALTER TYPE ... ADD VALUE inside a transaction block; it does not allow use.
-- golang-migrate hands each file to lib/pq as one argument-less Exec, which
-- travels over the simple query protocol and runs as a single implicit
-- transaction -- so one file is one transaction whether or not it writes its
-- own BEGIN/COMMIT, and splitting into two files is the only thing that works.
-- Dropping the BEGIN below would NOT make a single-file version legal.
--
-- Provenance: PokeAPI, fetched 2026-08-25.
--   pokemon 10278..10326          /api/v2/pokemon/{id}/
--   ability 308..313              /api/v2/ability/{id}/
--   pokedex 34 lumiose-city (232) /api/v2/pokedex/34/   -> dex label 'lumiose'
--   pokedex 35 hyperspace   (132) /api/v2/pokedex/35/
-- gender_rate, species_id and evolution chain_id are read from this database
-- rather than re-fetched: a Mega has no species of its own, so all three are
-- properties of its base species, which is already present.
--
-- Champions (version group 32) is deliberately excluded in full. It is the one
-- upstream source of learnsets for these Megas, so they land with no
-- movedetails; see the note above the abilitydetails section.

